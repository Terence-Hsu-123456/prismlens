const DICTS: Record<Lang, Dict> = { 'zh-CN': zh as unknown as Dict, 'en-US': en, 'ja-JP': ja }

export function translate(lang: Lang, key: DictKey): string {
  return DICTS[lang]?.[key] ?? DICTS['zh-CN'][key] ?? key
}

export function isLang(v: string | null | undefined): v is Lang {
  return v === 'zh-CN' || v === 'en-US' || v === 'ja-JP'
}

// 输出语言名（用于 AI 提示词）
export function langName(lang: Lang): string {
  if (lang === 'zh-CN') return '简体中文'
  if (lang === 'ja-JP') return '日本語'
  return 'English'
}
